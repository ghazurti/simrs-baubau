CREATE TABLE asesmen_keperawatan_invasif_non_bedah (
    no_rawat varchar(17) NOT NULL,
    tanggal datetime NOT NULL,
    jam_tiba_rr time NOT NULL,
    lokasi_pungsi varchar(50) NOT NULL,
    jumlah_pungsi varchar(10) NOT NULL,
    terpasang_sheath enum('Ya','Tidak') NOT NULL,
    lokasi_sheath varchar(50) NOT NULL,
    pulsasi_radialis_kanan varchar(20) NOT NULL,
    pulsasi_radialis_kiri varchar(20) NOT NULL,
    pulsasi_dorsalis_kanan varchar(20) NOT NULL,
    pulsasi_dorsalis_kiri varchar(20) NOT NULL,
    alat_terpasang varchar(150) NOT NULL,
    jenis_anestesi varchar(50) NOT NULL,
    sedasi varchar(50) NOT NULL,
    antikoagulan_dosis_pre varchar(50) NOT NULL,
    antikoagulan_dosis_intra varchar(50) NOT NULL,
    antikoagulan_dosis_post varchar(50) NOT NULL,
    komplikasi varchar(150) NOT NULL,
    balance_cairan_intake int(11) NOT NULL,
    balance_cairan_output int(11) NOT NULL,
    instruksi_paska_tindakan text NOT NULL,
    masalah_keperawatan text NOT NULL,
    rencana_keperawatan text NOT NULL,
    keputusan_rawat varchar(50) NOT NULL,
    nip varchar(20) NOT NULL,
    PRIMARY KEY (no_rawat, tanggal),
    KEY nip (nip),
    CONSTRAINT asesmen_keperawatan_invasif_non_bedah_ibfk_1 FOREIGN KEY (no_rawat) REFERENCES reg_periksa (no_rawat) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT asesmen_keperawatan_invasif_non_bedah_ibfk_2 FOREIGN KEY (nip) REFERENCES petugas (nip) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=latin1;

CREATE TABLE detail_ttv_invasif_non_bedah (
    no_rawat varchar(17) NOT NULL,
    tanggal datetime NOT NULL,
    jam_observasi time NOT NULL,
    bp_sistol varchar(10) NOT NULL,
    bp_diastol varchar(10) NOT NULL,
    nadi varchar(10) NOT NULL,
    rr varchar(10) NOT NULL,
    suhu varchar(10) NOT NULL,
    spo2 varchar(10) NOT NULL,
    pulsasi_distal varchar(30) NOT NULL,
    refleks_menelan varchar(30) NOT NULL,
    PRIMARY KEY (no_rawat, tanggal, jam_observasi),
    CONSTRAINT detail_ttv_invasif_non_bedah_ibfk_1 FOREIGN KEY (no_rawat, tanggal) REFERENCES asesmen_keperawatan_invasif_non_bedah (no_rawat, tanggal) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=latin1;
